const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

// Android pieces push needs (build-plan 38e1), applied only when the build
// has Firebase files (plugins/firebaseConfig.js):
// - `ic_notification`: the backend's FCM message names this small icon.
//   Android needs a white silhouette, or it draws a blank square. A Material
//   "notifications" bell stands in until design provides an Influsis mark.
// - expo-notifications is in the app only to create notification channels,
//   but it also declares its own FirebaseMessagingService. Two services for
//   com.google.firebase.MESSAGING_EVENT means only one gets the messages, so
//   its declaration is removed from the merged manifest and React Native
//   Firebase's service handles FCM.

const NOTIFICATION_ICON_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withPushAndroid.js. Material "notifications" icon (Apache 2.0). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24"
    android:tint="#FFFFFF">
  <path
      android:fillColor="#FFFFFF"
      android:pathData="M12,22c1.1,0 2,-0.9 2,-2h-4c0,1.1 0.89,2 2,2zM18,16v-5c0,-3.07 -1.64,-5.64 -4.5,-6.32L13.5,4c0,-0.83 -0.67,-1.5 -1.5,-1.5s-1.5,0.67 -1.5,1.5v0.68C7.63,5.36 6,7.92 6,11v5l-2,2v1h16v-1l-2,-2z" />
</vector>
`;

const EXPO_FCM_SERVICE = 'expo.modules.notifications.service.ExpoFirebaseMessagingService';

/**
 * Adds `<service android:name="…ExpoFirebaseMessagingService" tools:node="remove" />`
 * to the app manifest (xml2js shape) once. Pure, for tests.
 */
function removeExpoFcmService(androidManifest) {
  const manifest = androidManifest.manifest;
  manifest.$ = manifest.$ || {};
  manifest.$['xmlns:tools'] = manifest.$['xmlns:tools'] || 'http://schemas.android.com/tools';

  const application = manifest.application && manifest.application[0];
  if (!application) return androidManifest;
  application.service = application.service || [];
  const already = application.service.some(
    service => service.$ && service.$['android:name'] === EXPO_FCM_SERVICE,
  );
  if (!already) {
    application.service.push({
      $: { 'android:name': EXPO_FCM_SERVICE, 'tools:node': 'remove' },
    });
  }
  return androidManifest;
}

function withNotificationIcon(config) {
  return withDangerousMod(config, [
    'android',
    async cfg => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/res/drawable');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'ic_notification.xml'), NOTIFICATION_ICON_XML);
      return cfg;
    },
  ]);
}

function withoutExpoFcmService(config) {
  return withAndroidManifest(config, cfg => {
    cfg.modResults = removeExpoFcmService(cfg.modResults);
    return cfg;
  });
}

function withPushAndroid(config) {
  return withoutExpoFcmService(withNotificationIcon(config));
}

module.exports = withPushAndroid;
module.exports.removeExpoFcmService = removeExpoFcmService;
module.exports.NOTIFICATION_ICON_XML = NOTIFICATION_ICON_XML;
module.exports.EXPO_FCM_SERVICE = EXPO_FCM_SERVICE;
